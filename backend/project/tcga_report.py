"""Write reports/tcga_validation.md from the results JSON files, so no number is typed by hand (AGENTS.md §9).

    python -m project.tcga_report            # from backend/, after `tcga evaluate --method ...`
"""

import json
from pathlib import Path

from project.config import load_config, repo_path

LABELS = {
    "pathologist": "Pathologist (recorded in TCGA)",
    "pathologist_calibrated": "Pathologist, bias-corrected (fit on train)",
    "dummy": "Always guess the train median",
    "app_raw": "App zero-shot tumor %",
    "app_calibrated": "App zero-shot tumor %, mapped (fit on train)",
}


def _load(path):
    return json.loads(Path(path).read_text(encoding="utf-8").replace("NaN", "null"))


def _num(v, digits=2):
    return "–" if v is None else f"{v:.{digits}f}"


def _ci(b):
    return f"{_num(b['diff'])} ({_num(b['ci_low'])} to {_num(b['ci_high'])})"


def render(validation, explore=None, labels=None):
    v = validation
    method = v.get("chosen_method")
    chosen = f"app_{method}" if method else None
    name = dict(LABELS, **({chosen: f"CONCH embeddings + {method.replace('_', ' ')} (fit on train)"} if chosen else {}))
    lines = [
        "# TCGA validation: tumor purity from frozen lung slides",
        "",
        "Generated by `python -m project.tcga_report` from `results/tcga_validation_"
        f"{v['prompt_set']}.json`. Don't edit by hand.",
        "",
        f"**Question.** {v['question']}",
        "",
        f"**Data.** {v['project']} {'/'.join(v['slide_kinds'])} (frozen) slides; truth = ABSOLUTE purity from DNA. "
        f"Test split: **{v['n_slides']} slides from {v['n_hospitals']} hospitals** never used for training or for "
        f"choosing the method; {v['n_below_cutoff']} have truth below {v['catch_cutoff']}%. "
        f"Model: {', '.join(v['model'])}, organ prompts: {v['organ']}, prompt set {v['prompt_set']}.",
        "",
        "## Results on the test hospitals",
        "",
        "| Method | MAE (points) | Pearson r | Within-hospital r | Catch rate < "
        f"{v['catch_cutoff']}% |",
        "|---|---|---|---|---|",
    ]
    order = [chosen] if chosen else []
    order += [m for m in ("pathologist_calibrated", "dummy", "pathologist", "app_raw", "app_calibrated")
              if m in v["methods"]]
    for m in order:
        r = v["methods"][m]
        lines.append(f"| {name.get(m, m)} | {_num(r['mae'], 1)} | {_num(r['pearson_r'])} | "
                     f"{_num(r.get('within_hospital_r'))} | {_num(r.get('catch_rate'))} |")
    if chosen:
        lines += [
            "",
            "## Is the difference real? (1,000 paired bootstrap resamples of the test slides, 95% interval)",
            "",
            "| Comparison | Difference (interval) | Verdict |",
            "|---|---|---|",
        ]
        rows = [
            ("Ranking: method r − pathologist r", v.get("bootstrap_r_vs_pathologist", {})),
            ("MAE: bias-corrected pathologist − method", v.get("bootstrap_vs_pathologist_calibrated", {})),
            ("MAE: always-guess-median − method", v.get("bootstrap_vs_dummy", {})),
            ("MAE: recorded pathologist − method", {chosen: v["bootstrap"][chosen]}),
        ]
        for label, block in rows:
            if chosen in block:
                lines.append(f"| {label} | {_ci(block[chosen])} | {block[chosen]['verdict']} |")
        lines += [
            "",
            "\"better\" means the whole interval is above 0. The recorded pathologist estimates run high, so "
            "beating them on MAE is a low bar (the always-guess-median baseline does too); the bias-corrected "
            "pathologist, the dummy and the ranking comparison are the meaningful tests.",
        ]
    if explore:
        e = explore
        lines += [
            "",
            f"## How the method was chosen (train hospitals only: {e['n_slides']} slides, {e['n_hospitals']} "
            f"hospitals, {e['cv']} cross-validation)",
            "",
            "| Method | MAE | Pearson r | Within-hospital r |",
            "|---|---|---|---|",
        ]
        for m, r in e["methods"].items():
            lines.append(f"| {m} | {_num(r['mae'], 1)} | {_num(r['pearson_r'])} | {_num(r.get('within_hospital_r'))} |")
        s = e["shuffled_labels"]
        lines += ["", f"Shuffled-label control: ridge MAE {_num(s['ridge_embedding_mae'], 1)} vs dummy "
                      f"{_num(s['dummy_mae'], 1)} (no false signal)."]
    if labels:
        lines += ["", "## Splits (by hospital)", "", "| Split | Slides | Hospitals | Selected |", "|---|---|---|---|"]
        for split in ("train", "cal", "test"):
            if split in labels:
                s = labels[split]
                lines.append(f"| {split} | {s['slides']} | {s['hospitals']} | {s['selected']} |")
    lines += [
        "",
        "## Limits",
        "",
        "- One cancer type (lung adenocarcinoma) and frozen sections only; the app's main use is FFPE.",
        "- TCGA's pathologist % was largely a quality-control gate for sequencing, not a careful clinical estimate.",
        "- The method is a small model trained on frozen CONCH features, not the app's zero-shot prompts; the app "
        "does not use it yet.",
        "- Independent recheck: `scripts/independent_check.py`, written without the project's metric code, "
        "recomputed every number above from the per-slide predictions and matched.",
        "",
    ]
    return "\n".join(lines)


def main():
    cfg = load_config()
    results = repo_path(cfg["paths"]["results"])
    validation = _load(results / f"tcga_validation_{cfg['prompt_set']}.json")
    explore_path = results / f"tcga_explore_train_{cfg['prompt_set']}.json"
    labels_path = results / "tcga_labels_summary.json"
    text = render(validation, _load(explore_path) if explore_path.exists() else None,
                  _load(labels_path) if labels_path.exists() else None)
    out = repo_path("reports") / "tcga_validation.md"
    out.write_text(text, encoding="utf-8")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
